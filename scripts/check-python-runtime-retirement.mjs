#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/**
 * Repository policy for keeping EmuChef's product and developer workflows
 * independent from the retired Python implementation. The guard inspects the
 * working tree as well as tracked files so local reintroductions fail before
 * they are staged.
 */
export const TOOLING_PYTHON_ALLOWLIST = Object.freeze([]);

const PYTHON_FILE_RE = /(?:^|\/)(?:__pycache__)(?:\/|$)|\.(?:py|pyi|pyw|pyc|pyo)$/i;
const PYTHON_PROJECT_FILE_RE = /(?:^|\/)(?:pyproject\.toml|setup\.py|setup\.cfg|tox\.ini|Pipfile(?:\.lock)?|poetry\.lock|uv\.lock|requirements(?:[-_.][^/]*)?\.txt)$/i;
const ACTIVE_RUNTIME_FILE_RE = /(?:^|\/)(?:package\.json|Cargo\.toml|tauri(?:\.[^.]+)?\.conf\.json|[^/]+\.(?:rs|js|mjs|cjs|ts|tsx|sh|bash|zsh))$/i;
const WORKFLOW_FILE_RE = /^\.github\/workflows\/[^/]+\.ya?ml$/i;
const TEST_PATH_RE = /(?:^|\/)(?:tests?|fixtures)(?:\/|$)|\.(?:test|spec)\.[^/]+$/i;
const NEGATIVE_ENFORCEMENT_PATHS = new Set([
  "apps/config-editor/scripts/check-macos-bundle.mjs",
  "apps/config-editor/scripts/check-macos-bundle.test.mjs",
  "scripts/check-python-runtime-retirement.mjs",
  "scripts/check-python-runtime-retirement.test.mjs",
]);

const FORBIDDEN_RUNTIME_PATTERNS = [
  [/(?<![A-Za-z0-9_.-])(python3?(?:\.exe)?|uv(?:\.exe)?)(?![A-Za-z0-9_.-])/g, "Python or uv command"],
  [/(?:^|\s)-m\s+(emuchef(?:_editor)?)(?![A-Za-z0-9_.-])/gm, "Python module entrypoint"],
  [/(?<![A-Za-z0-9_.-])(emuchef_editor\.api\.server|python_bridge|PySide6)(?![A-Za-z0-9_.-])/g, "Python runtime module"],
  [/(?<![A-Za-z0-9_.-])(emuchef-python-legacy|emuchef-plan-shadow|plan_shadow)(?![A-Za-z0-9_.-])/g, "retired runtime name"],
  [/(?<![A-Za-z0-9_.-])(--backend|--python-(?:backend|runtime|planner)(?:-bin)?|--rust-(?:backend|runtime|planner)(?:-bin)?)(?![A-Za-z0-9_.-])/g, "backend selector or compatibility flag"],
  [/(?<![A-Za-z0-9_])(EMUCHEF_[A-Z0-9_]*(?:PYTHON|BACKEND)[A-Z0-9_]*)(?![A-Za-z0-9_])/g, "backend-selection environment variable"],
];

/** Convert platform-specific paths to stable repository-relative paths. */
export function normalizeRepositoryPath(filePath) {
  return filePath.split(path.sep).join("/").replaceAll("\\", "/").replace(/^\.\//, "");
}

/** Return whether a path is prohibited Python source or generated bytecode. */
export function isPythonArtifactPath(filePath) {
  const normalizedPath = normalizeRepositoryPath(filePath);
  return PYTHON_FILE_RE.test(normalizedPath) && !TOOLING_PYTHON_ALLOWLIST.includes(normalizedPath);
}

/** Return whether a path declares a Python project or dependency environment. */
export function isPythonProjectPath(filePath) {
  return PYTHON_PROJECT_FILE_RE.test(normalizeRepositoryPath(filePath));
}

/** Select active build/runtime surfaces while excluding tests and negative checks. */
export function shouldScanRuntimeContent(filePath) {
  const normalizedPath = normalizeRepositoryPath(filePath);
  return (ACTIVE_RUNTIME_FILE_RE.test(normalizedPath) || WORKFLOW_FILE_RE.test(normalizedPath))
    && !TEST_PATH_RE.test(normalizedPath)
    && !NEGATIVE_ENFORCEMENT_PATHS.has(normalizedPath);
}

/**
 * Remove Rust cfg-test modules before token scanning. Tests may name prohibited
 * commands to prove negative behavior without making them runtime paths.
 */
export function stripRustTestModules(content) {
  const marker = /(?:^|\n)\s*#\[cfg\(test\)\]\s*\n\s*mod\s+[A-Za-z0-9_]+\s*\{/g;
  let output = "";
  let cursor = 0;
  for (const match of content.matchAll(marker)) {
    const start = match.index;
    output += content.slice(cursor, start);
    let braceIndex = content.indexOf("{", start);
    let balance = 0;
    while (braceIndex < content.length) {
      if (content[braceIndex] === "{") balance += 1;
      if (content[braceIndex] === "}") balance -= 1;
      braceIndex += 1;
      if (balance === 0) break;
    }
    cursor = braceIndex;
  }
  return output + content.slice(cursor);
}

/** Find prohibited runtime commands, modules, selectors, and legacy names. */
export function findForbiddenRuntimeTokens(filePath, content) {
  if (!shouldScanRuntimeContent(filePath)) return [];
  const normalizedPath = normalizeRepositoryPath(filePath);
  const runtimeContent = normalizedPath.endsWith(".rs") ? stripRustTestModules(content) : content;
  const hits = [];
  for (const [pattern, reason] of FORBIDDEN_RUNTIME_PATTERNS) {
    pattern.lastIndex = 0;
    for (const match of runtimeContent.matchAll(pattern)) {
      hits.push({
        path: normalizedPath,
        line: runtimeContent.slice(0, match.index).split("\n").length,
        token: match[1],
        reason,
      });
    }
  }
  return hits;
}

/** Classify repository entries and return a deterministic violation list. */
export function analyzeRepositoryEntries(entries) {
  const hits = [];
  for (const entry of entries) {
    const normalizedPath = normalizeRepositoryPath(entry.path);
    if (isPythonArtifactPath(normalizedPath)) {
      hits.push({ path: normalizedPath, line: 0, token: normalizedPath, reason: "Python source or bytecode" });
    }
    if (isPythonProjectPath(normalizedPath)) {
      hits.push({ path: normalizedPath, line: 0, token: normalizedPath, reason: "Python project metadata" });
    }
    hits.push(...findForbiddenRuntimeTokens(normalizedPath, entry.content ?? ""));
  }
  return hits.sort((left, right) => left.path.localeCompare(right.path) || left.line - right.line || left.token.localeCompare(right.token));
}

/** List tracked and non-ignored working-tree files without relying on staging. */
export function listRepositoryFiles(repoRoot) {
  return execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    { cwd: repoRoot, encoding: "utf8" },
  ).split("\0").filter(Boolean).map(normalizeRepositoryPath);
}

/** Read only regular files needed for structural or runtime-token analysis. */
export function readRepositoryEntries(repoRoot, files = listRepositoryFiles(repoRoot)) {
  const entries = [];
  for (const filePath of files) {
    const absolutePath = path.join(repoRoot, filePath);
    if (!fs.existsSync(absolutePath)) continue;
    const metadata = fs.lstatSync(absolutePath);
    if (!metadata.isFile()) continue;
    const content = shouldScanRuntimeContent(filePath) ? fs.readFileSync(absolutePath, "utf8") : "";
    entries.push({ path: filePath, content });
  }
  return entries;
}

/** Run the complete retirement policy against a repository root. */
export function runRetirementGuard(repoRoot) {
  return analyzeRepositoryEntries(readRepositoryEntries(repoRoot));
}

/** Execute the command-line guard and return its process exit status. */
export function main({
  repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."),
  writeError = console.error,
  writeOutput = console.log,
} = {}) {
  const hits = runRetirementGuard(repoRoot);
  if (hits.length > 0) {
    writeError("check-python-runtime-retirement: prohibited Python runtime surface found:");
    for (const hit of hits) {
      const location = hit.line > 0 ? `${hit.path}:${hit.line}` : hit.path;
      writeError(`- ${location}: ${hit.reason}: ${hit.token}`);
    }
    return 1;
  }
  writeOutput("check-python-runtime-retirement: no Python product/runtime surface or backend-selection path found.");
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main();
